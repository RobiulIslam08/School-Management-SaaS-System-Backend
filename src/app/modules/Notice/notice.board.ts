export async function ensureNoticeBoard(): Promise<void> {
  const existing = new Set(
    (await Notice.find({ refNo: /^NB-2026-/ }).select("refNo").lean()).map((row) => String(row.refNo))
  );
  const start = Date.UTC(2026, 0, 8);
  const fresh = ROWS.flatMap((row, index) => {
    const refNo = `NB-2026-${String(index + 1).padStart(3, "0")}`;
    if (existing.has(refNo)) return [];
    return [{
      title: row.title,
      body: row.body,
      audience: "all" as const,
      isPublished: true,
      showOnWebsite: true,
      category: row.category,
      pinned: Boolean(row.pinned),
      refNo,
      issueDate: new Date(start + index * 5 * 24 * 60 * 60 * 1000),
      signatories: [{ name: "নুরুল ইসলাম", designation: "প্রধান শিক্ষক" }],
      createdByName: "অফিস",
    }];
  });
  if (fresh.length) await Notice.insertMany(fresh);
  const rows = await Notice.find({ refNo: /^NB-2026-/ }).select("_id refNo").sort({ createdAt: 1 }).lean();
  const seen = new Set<string>();
  const extra: string[] = [];
  for (const row of rows) {
    const ref = String(row.refNo);
    if (seen.has(ref)) extra.push(String(row._id));
    else seen.add(ref);
  }
  if (extra.length) await Notice.deleteMany({ _id: { $in: extra } });
}
